"""The trust-store rule (email_mcp.tls) and the smtp driver's use of it.

Background (2026-09-14): python.org framework builds ship no root-CA
bundle, so ``ssl.create_default_context()`` holds zero anchors and every
verified handshake fails with CERTIFICATE_VERIFY_FAILED — the Gmail lane
broke the moment 2d6b9a9 switched peer verification on. Graph had solved
the same environment problem alone on 2026-07-29; now both lanes share
one rule, and the smtp driver names the certificate verdict instead of
suggesting the VPN.

Two layers: unit tests pin the source-selection rule and the error
mapping with monkeypatched seams; the real-handshake tests drive the
driver's own ``_connect`` against a local TLS SMTP server with a test CA
generated by the ``openssl`` CLI — the only way to prove verification
happens against an actual chain (the mocked context tests cannot).
"""
from __future__ import annotations

import shutil
import socket
import ssl
import subprocess
import threading
from pathlib import Path

import pytest

from email_mcp import codes, tls
from email_mcp.transports import SendError
from email_mcp.transports import smtp as smtp_mod
from email_mcp.transports.smtp import SmtpTransport


