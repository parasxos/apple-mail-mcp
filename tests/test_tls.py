def test_empty_store_is_refused_before_any_connection(monkeypatch, no_env):
    """Zero anchors and none configured: connecting is pointless and the
    remedy is local. Refuse up front, before the socket, the password or
    the message."""
    monkeypatch.setattr(tls, "_system_store", lambda: (None, None))
    monkeypatch.setattr(tls, "_certifi_bundle", lambda: None)
    monkeypatch.setattr(
        smtp_mod.smtplib, "SMTP",
        lambda *a, **k: pytest.fail("must not connect with an empty store"))
    monkeypatch.setattr(smtp_mod, "_read_keychain", lambda item, account: "pw")
    t = _smtp(port=587)
    with pytest.raises(SendError) as ei:
        t.deliver(_RAW, "g@example.org", ["a@example.org"])
    assert ei.value.code == codes.TRANSPORT_UNAVAILABLE
    assert "certifi" in str(ei.value)
    assert t.ensure() is False and "certifi" in t.last_ensure_error
    hc = t.healthcheck()
    assert hc["ok"] is False and "certifi" in hc["fix"]


