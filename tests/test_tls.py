def _verify_error(code: int, message: str) -> ssl.SSLCertVerificationError:
    e = ssl.SSLCertVerificationError(
        1, f"[SSL: CERTIFICATE_VERIFY_FAILED] certificate verify failed: "
           f"{message} (_ssl.c:992)")
    e.verify_code = code
    e.verify_message = message
    return e


@pytest.mark.parametrize("code, message, expect", [
    (20, "unable to get local issuer certificate", "no issuer"),
    (19, "self-signed certificate in certificate chain", "no issuer"),
    (10, "certificate has expired", "validity period"),
    (62, "Hostname mismatch, certificate is not valid for 'x'", "host name"),
    (7, "certificate signature failure", "verification failed"),
])
def test_failure_line_carries_the_verdict_and_a_matching_hint(
    monkeypatch, no_env, code, message, expect,
):
    """OpenSSL's verify_message/verify_code, the store that judged it,
    and a hint that follows from THAT verdict — never a diagnosis
    (interception, wrong host) asserted from a nonzero root count."""
    monkeypatch.setattr(tls, "_system_store", lambda: (None, None))
    ctx = tls.client_context()
    line = tls.failure(ctx, _verify_error(code, message))
    assert message in line and f"verify code {code}" in line
    assert "roots loaded from certifi" in line
    assert expect in line
    assert "VPN" not in line


