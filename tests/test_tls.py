def test_explicitly_empty_env_values_are_a_configuration_too(monkeypatch):
    """SSL_CERT_FILE='' SSL_CERT_DIR='' is how an operator says "trust
    nothing from the defaults". Presence counts, not truthiness: no
    certifi, zero roots, and the handshake fails as configured."""
    import certifi
    monkeypatch.setenv("SSL_CERT_FILE", "")
    monkeypatch.setenv("SSL_CERT_DIR", "")
    calls = []
    monkeypatch.setattr(tls, "_certifi_bundle",
                        lambda: calls.append(1) or None)
    monkeypatch.setattr(tls, "_system_store",
                        lambda: (certifi.where(), None))  # must stay unused
    ctx = tls.client_context()
    assert tls.describe(ctx) == {"roots": 0, "source": tls.SOURCE_ENV}
    assert calls == []
    assert ctx.verify_mode == ssl.CERT_REQUIRED and ctx.check_hostname


def test_verification_settings_match_the_running_interpreter(monkeypatch, no_env):
    """Only the trust loading is ours. verify_flags (3.13+ adds
    VERIFY_X509_STRICT and VERIFY_X509_PARTIAL_CHAIN; older interpreters
    keep theirs), options and the TLS version bounds must equal what
    create_default_context() sets on THIS interpreter — parity, not a
    hard-coded flag list, and no silent weakening on either side."""
    import certifi
    ref = ssl.create_default_context()
    monkeypatch.setattr(tls, "_system_store", lambda: (None, None))
    for ctx in (tls.client_context(), tls.client_context(cafile=certifi.where())):
        assert ctx.verify_mode == ssl.CERT_REQUIRED and ctx.check_hostname
        assert ctx.verify_flags == ref.verify_flags
        assert ctx.options == ref.options
        assert (ctx.minimum_version, ctx.maximum_version) == \
            (ref.minimum_version, ref.maximum_version)


def _spy_load(monkeypatch):
    seen: list[tuple] = []
    real = tls._load

    def spy(ctx, cafile, capath):
        seen.append((cafile, capath))
        return real(ctx, cafile, capath)

    monkeypatch.setattr(tls, "_load", spy)
    return seen


def test_only_ssl_cert_dir_keeps_the_default_cafile(monkeypatch, tmp_path):
    """OpenSSL semantics: each variable replaces its own component. A
    private hashed directory added through SSL_CERT_DIR must not throw
    away the public roots in the default cafile."""
    import certifi
    extra = tmp_path / "private"
    extra.mkdir()
    monkeypatch.setenv("SSL_CERT_DIR", str(extra))
    monkeypatch.delenv("SSL_CERT_FILE", raising=False)
    monkeypatch.setattr(tls, "_system_store", lambda: (certifi.where(), None))
    seen = _spy_load(monkeypatch)
    ctx = tls.client_context()
    info = tls.describe(ctx)
    assert info["source"] == tls.SOURCE_ENV and info["roots"] > 0
    assert seen == [(certifi.where(), str(extra))]


