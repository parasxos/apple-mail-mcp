def test_hashed_directory_reads_zero_roots_and_still_verifies(
    live, monkeypatch, pki,
):
    """SSL_CERT_DIR: OpenSSL loads a hashed directory lazily, so the
    store reads 0 roots before the first handshake — and verifies fine.
    A zero count must never be mistaken for an absent store. The cafile
    component is emptied explicitly so only the directory is in play
    on any host (SSL_CERT_DIR alone would keep the default cafile)."""
    monkeypatch.setenv("SSL_CERT_FILE", "")
    monkeypatch.setenv("SSL_CERT_DIR", str(pki["capath"]))
    ctx = tls.client_context()
    assert tls.describe(ctx) == {"roots": 0, "source": tls.SOURCE_ENV}
    assert not tls.empty(ctx)
    t, srv = live("localhost", implicit=False)
    assert t.ensure() is True, t.last_ensure_error
    # The context that judged the peer now shows what the handshake
    # loaded from the directory — that is the one the driver keeps.
    assert tls.describe(t._ctx) == {"roots": 1, "source": tls.SOURCE_ENV}


def test_intermediate_anchor_behaves_exactly_like_create_default_context(
    live, monkeypatch, pki,
):
    """Trusting ONLY the intermediate of a root -> intermediate -> leaf
    chain is accepted where the interpreter's create_default_context
    sets VERIFY_X509_PARTIAL_CHAIN (3.13+) and rejected where it does
    not. The driver must do exactly what the reference does on THIS
    interpreter — measured, not assumed, with one real handshake each."""
    chain = {"leaf": pki["chain2"], "key": pki["key2"]}
    ref = ssl.create_default_context(cafile=str(pki["intermediate"]))
    srv = _TlsSmtpServer(chain, implicit=True)
    try:
        with socket.create_connection(("127.0.0.1", srv.port), timeout=10) as raw:
            with ref.wrap_socket(raw, server_hostname="localhost"):
                ref_ok = True
    except ssl.SSLCertVerificationError:
        ref_ok = False
    finally:
        srv.close()
    assert ref_ok == bool(ref.verify_flags & ssl.VERIFY_X509_PARTIAL_CHAIN)

    monkeypatch.setenv("SSL_CERT_FILE", str(pki["intermediate"]))
    monkeypatch.setenv("SSL_CERT_DIR", "")  # nothing else, on any host
    for implicit in (True, False):
        t, srv = live("localhost", implicit=implicit, chain=chain)
        assert t.ensure() is ref_ok, t.last_ensure_error
        if not ref_ok:
            assert "verify code" in t.last_ensure_error
