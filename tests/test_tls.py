def test_framework_python_without_a_store_falls_back_to_certifi(
    monkeypatch, no_env,
):
    """The observed Gmail failure: default paths absent → certifi's bundle
    is loaded and reported; verification stays strict."""
    monkeypatch.setattr(tls, "_system_store", lambda: (None, None))
    ctx = tls.client_context()
    info = tls.describe(ctx)
    assert info["source"] == tls.SOURCE_CERTIFI
    assert info["roots"] > 0
    assert ctx.verify_mode == ssl.CERT_REQUIRED and ctx.check_hostname
    assert not tls.empty(ctx)


def test_a_default_hashed_directory_is_used_even_when_it_reads_empty(
    monkeypatch, no_env, tmp_path,
):
    """A default capath is a hashed directory: it loads lazily and reads
    zero anchors until a handshake touches it. That is a usable store,
    not a missing one — certifi must not be piled on top."""
    capath = tmp_path / "certs"
    capath.mkdir()
    (capath / "deadbeef.0").write_text("placeholder entry\n")
    monkeypatch.setattr(tls, "_system_store", lambda: (None, str(capath)))
    calls = []
    monkeypatch.setattr(tls, "_certifi_bundle",
                        lambda: calls.append(1) or None)
    ctx = tls.client_context()
    assert tls.describe(ctx) == {"roots": 0, "source": tls.SOURCE_SYSTEM}
    assert calls == []  # never consulted


def test_a_default_cafile_that_yields_no_anchor_falls_through_to_certifi(
    monkeypatch, no_env, tmp_path,
):
    """Different from a lazy directory: a default cafile that exists but
    holds no CA certificate is the empty-default install, and leaving it
    as "system" would suppress the fallback forever (and regress Graph,
    which used to reach certifi in exactly this state)."""
    bundle = tmp_path / "cert.pem"
    bundle.write_text("# no certificates in here\n")
    monkeypatch.setattr(tls, "_system_store", lambda: (str(bundle), None))
    ctx = tls.client_context()
    info = tls.describe(ctx)
    assert info["source"] == tls.SOURCE_CERTIFI and info["roots"] > 0


def test_system_store_seam_ignores_paths_that_exist_but_are_empty(
    monkeypatch, tmp_path,
):
    """ssl.get_default_verify_paths() can name an empty file and an empty
    directory (a bare OpenSSL layout with nothing installed); neither
    is usable. A directory with an entry is."""
    empty_file = tmp_path / "cert.pem"
    empty_file.write_text("")
    empty_dir = tmp_path / "certs"
    empty_dir.mkdir()
    fake = ssl.DefaultVerifyPaths(
        cafile=None, capath=None,
        openssl_cafile_env="SSL_CERT_FILE", openssl_cafile=str(empty_file),
        openssl_capath_env="SSL_CERT_DIR", openssl_capath=str(empty_dir))
    monkeypatch.setattr(tls.ssl, "get_default_verify_paths", lambda: fake)
    assert tls._system_store() == (None, None)
    (empty_dir / "deadbeef.0").write_text("x")
    assert tls._system_store() == (None, str(empty_dir))
    missing = fake._replace(openssl_cafile="/nonexistent/cert.pem",
                            openssl_capath="/nonexistent/certs")
    monkeypatch.setattr(tls.ssl, "get_default_verify_paths", lambda: missing)
    assert tls._system_store() == (None, None)


