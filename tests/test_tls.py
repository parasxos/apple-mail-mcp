def _smtp(**kw) -> SmtpTransport:
    defaults = dict(identity="gmail", from_addr="g@example.org",
                    host="smtp.example.org", keychain="email-mcp-g")
    defaults.update(kw)
    return SmtpTransport(**defaults)


_RAW = (b"From: g@example.org\r\nTo: a@example.org\r\nSubject: s\r\n"
        b"Message-ID: <m@x>\r\n\r\nbody\r\n")


def _rejecting_smtp_cls(exc: BaseException):
    """smtplib.SMTP stand-in whose STARTTLS fails verification."""
    class Fake:
        instances: list = []

        def __init__(self, host, port, timeout=None, context=None):
            self.calls: list = []
            self.closed = False
            Fake.instances.append(self)

        def starttls(self, context=None):
            self.calls.append(("starttls", context))
            raise exc

        def ehlo(self):
            self.calls.append(("ehlo",))

        def login(self, *a):
            self.calls.append(("login",))

        def sendmail(self, *a):
            self.calls.append(("sendmail",))

        def close(self):
            self.closed = True

        def quit(self):
            self.calls.append(("quit",))

    return Fake


def test_deliver_maps_verification_failure_to_transport_unavailable(
    monkeypatch, no_env,
):
    """Not delivery_failed with a VPN hint: nothing was sent, no secret
    was spoken, and the same handshake fails on every retry. The lane is
    unavailable and the message says why, in OpenSSL's words."""
    monkeypatch.setattr(tls, "_system_store", lambda: (None, None))
    Fake = _rejecting_smtp_cls(
        _verify_error(20, "unable to get local issuer certificate"))
    monkeypatch.setattr(smtp_mod.smtplib, "SMTP", Fake)
    monkeypatch.setattr(smtp_mod, "_read_keychain", lambda item, account: "pw")
    with pytest.raises(SendError) as ei:
        _smtp(port=587).deliver(_RAW, "g@example.org", ["a@example.org"])
    assert ei.value.code == codes.TRANSPORT_UNAVAILABLE
    text = str(ei.value)
    assert "[gmail/smtp] TLS certificate verification of smtp.example.org:587 failed" in text
    assert "unable to get local issuer certificate" in text
    assert "VPN" not in text
    fake = Fake.instances[0]
    assert fake.closed                      # _connect closed what it opened
    assert ("login",) not in fake.calls and ("sendmail",) not in fake.calls


